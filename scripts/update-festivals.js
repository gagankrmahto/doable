// Builds web/data/festivals.js from Google's public "Holidays in India" calendar.
//   node scripts/update-festivals.js            (downloads the feed)
//   node scripts/update-festivals.js feed.ics   (uses a local copy)
// Runs monthly in CI (.github/workflows/festivals.yml) so new years appear automatically.
const fs = require('fs');
const path = require('path');

const FEED = 'https://calendar.google.com/calendar/ical/en.indian%23holiday%40group.v.calendar.google.com/public/basic.ics';
const OUT = path.join(__dirname, '..', 'web', 'data', 'festivals.js');
const FROM_YEAR = new Date().getFullYear() - 1;
// Friendlier names for a few feed titles
const RENAME = {
  'Karaka Chaturthi': 'Karva Chauth',
  'Chhat Puja (Pratihar Sashthi/Surya Sashthi)': 'Chhath Puja',
  'Diwali/Deepavali': 'Diwali',
  'Ramzan Id': 'Eid ul-Fitr',
  'Bakrid': 'Eid ul-Adha (Bakrid)',
  'Milad un-Nabi': 'Milad-un-Nabi',
  'Naraka Chaturdasi': 'Naraka Chaturdashi (Choti Diwali)',
  'Birthday of Rabindranath': 'Rabindranath Tagore Jayanti',
};

async function main() {
  const src = process.argv[2];
  const ics = src ? fs.readFileSync(src, 'utf8') : await (await fetch(FEED)).text();
  if (!ics.includes('BEGIN:VCALENDAR')) throw new Error('Not an iCalendar feed');
  const text = ics.replace(/\r\n[ \t]/g, '').replace(/\r/g, '');
  const seen = new Set();
  const events = [];
  for (const block of text.split('BEGIN:VEVENT').slice(1)) {
    const d = (block.match(/DTSTART;VALUE=DATE:(\d{4})(\d{2})(\d{2})/) || []).slice(1).join('-');
    const t = ((block.match(/\nSUMMARY:([^\n]*)/) || [])[1] || '').replace(/\\,/g, ',').replace(/\\;/g, ';').trim();
    const desc = (block.match(/\nDESCRIPTION:([^\n]*)/) || [])[1] || '';
    if (!d || !t || +d.slice(0, 4) < FROM_YEAR) continue;
    const base = t.replace(/\s*\((Smarta|Vaishnava)\)$/, ''); // same festival listed twice by tradition
    const name = RENAME[base] || base;
    const key = `${d}|${name}`;
    if (seen.has(key)) continue;
    seen.add(key);
    const e = { d, t: name, k: /^Public holiday/.test(desc) ? 'holiday' : 'observance' };
    if (/tentative/i.test(desc)) e.tentative = true;
    events.push(e);
  }
  events.sort((a, b) => a.d.localeCompare(b.d) || a.t.localeCompare(b.t));
  const years = [...new Set(events.map(e => e.d.slice(0, 4)))];
  const body = events.map(e => '  ' + JSON.stringify(e)).join(',\n');
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, `// Generated by scripts/update-festivals.js from Google's public "Holidays in India" calendar. Do not edit by hand.\n// Years: ${years.join(', ')}\nwindow.DOABLE_FESTIVALS = [\n${body},\n];\n`);
  console.log(`${events.length} festivals (${years[0]}–${years[years.length - 1]}) → ${path.relative(process.cwd(), OUT)}`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
